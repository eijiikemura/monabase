const eventChannels = new Set(["ai-response-chunk","ai-usage-history-updated","focus-diagnostics"]);

contextBridge.exposeInMainWorld('monaBase', {
  invoke(channel, ...args) {
    if (!invokeChannels.has(channel)) return Promise.reject(new Error('Unsupported IPC channel.'));
    return ipcRenderer.invoke(channel, ...args);
  },
  on(channel, listener) {
    if (!eventChannels.has(channel) || typeof listener !== 'function') throw new Error('Unsupported IPC event.');
    // Native IPC events expose privileged objects; forward payloads only.
    const wrapped = (_event, ...args) => listener(undefined, ...args);
    ipcRenderer.on(channel, wrapped);
    // Return cleanup directly instead of comparing callbacks across isolated contexts.
    let active = true;
    return () => {
      if (active) ipcRenderer.removeListener(channel, wrapped);
      active = false;
    };
  }
});
