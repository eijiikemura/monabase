// Render the Trace guide's detailed tables as sections so they follow the DB notes.
// Keep the same table markup and escaping as scripts/generate-content.mjs.
function traceTableSection(table: { title: string; description: string; headers: string[]; rows: string[][] }) {
  const cell = (value: string) => value.replaceAll('|', '\\|').replaceAll('\n', ' ');
  if (table.headers.length < 2 || table.rows.some(row => row.length !== table.headers.length)) {
    throw new Error(`Invalid Trace manual table dimensions: ${table.title}`);
  }
  const markdown = [
    `| ${table.headers.map(cell).join(' | ')} |`,
    `| ${table.headers.map(() => '---').join(' | ')} |`,
    ...table.rows.map(row => `| ${row.map(cell).join(' | ')} |`),
  ].join('\n');
  return {
    title: table.title,
    body: `${table.description}\n\n<div class="manual-table-scroll" role="region" aria-label={${JSON.stringify(table.title)}} tabindex={0}>\n\n${markdown}\n\n</div>`,
  };
}

